def emphasized_parts(line: str) -> list[tuple[str, bool]]:
    """줄을 (글, 굵게?) 조각으로 나눈다. 「 」 안의 단추·칸 이름이 굵게다(괄호는 굵지 않은 쪽에 남긴다)."""
    parts: list[tuple[str, bool]] = []
    rest = line
    while "「" in rest and "」" in rest[rest.index("「") :]:
        start = rest.index("「")
        end = rest.index("」", start)
        parts += [(rest[: start + 1], False), (rest[start + 1 : end], True)]
        rest = rest[end:]
    parts.append((rest, False))
    return [(text, bold) for text, bold in parts if text]
